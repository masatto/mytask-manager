-- docs/db-design.md v1.0 に対応する初期スキーマ

CREATE TABLE recurrence_rules (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title               VARCHAR(200)             NOT NULL,
    memo                VARCHAR(10000),
    priority            VARCHAR(10)              NOT NULL,
    due_time            TIME,
    pattern_type        VARCHAR(10)              NOT NULL,
    days_of_week        VARCHAR(27),
    day_of_month        INTEGER,
    start_date          DATE                     NOT NULL,
    end_date            DATE,
    active              BOOLEAN                  NOT NULL,
    last_generated_date DATE,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_rules_priority CHECK (priority IN ('HIGH', 'MEDIUM', 'LOW')),
    CONSTRAINT ck_rules_pattern CHECK (
        (pattern_type = 'DAILY'   AND days_of_week IS NULL     AND day_of_month IS NULL) OR
        (pattern_type = 'WEEKLY'  AND days_of_week IS NOT NULL AND day_of_month IS NULL) OR
        (pattern_type = 'MONTHLY' AND days_of_week IS NULL     AND day_of_month IS NOT NULL)
    ),
    CONSTRAINT ck_rules_day_of_month CHECK (
        day_of_month IS NULL OR day_of_month = -1 OR day_of_month BETWEEN 1 AND 31
    ),
    CONSTRAINT ck_rules_period CHECK (end_date IS NULL OR end_date >= start_date)
);

CREATE TABLE rule_subtask_templates (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_id  BIGINT       NOT NULL,
    position INTEGER      NOT NULL,
    title    VARCHAR(200) NOT NULL,
    priority VARCHAR(10)  NOT NULL,
    CONSTRAINT fk_templates_rule FOREIGN KEY (rule_id)
        REFERENCES recurrence_rules (id) ON DELETE CASCADE,
    CONSTRAINT uq_templates_position UNIQUE (rule_id, position),
    CONSTRAINT ck_templates_priority CHECK (priority IN ('HIGH', 'MEDIUM', 'LOW'))
);

CREATE TABLE tasks (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title              VARCHAR(200)             NOT NULL,
    memo               VARCHAR(10000),
    due_date           DATE,
    due_time           TIME,
    priority           VARCHAR(10)              NOT NULL,
    status             VARCHAR(12)              NOT NULL,
    completed_at       TIMESTAMP WITH TIME ZONE,
    parent_id          BIGINT,
    level              TINYINT                  NOT NULL,
    parent_level       TINYINT,
    recurrence_rule_id BIGINT,
    occurrence_date    DATE,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_tasks_due_time CHECK (due_time IS NULL OR due_date IS NOT NULL),
    CONSTRAINT ck_tasks_completed CHECK ((status = 'DONE') = (completed_at IS NOT NULL)),
    CONSTRAINT ck_tasks_priority CHECK (priority IN ('HIGH', 'MEDIUM', 'LOW')),
    CONSTRAINT ck_tasks_status CHECK (status IN ('TODO', 'IN_PROGRESS', 'DONE')),
    -- サブタスクの入れ子禁止（db-design 3.4）：サブタスクは level=0 の行しか参照できない
    CONSTRAINT ck_tasks_level CHECK (
        (parent_id IS NULL     AND level = 0 AND parent_level IS NULL) OR
        (parent_id IS NOT NULL AND level = 1 AND parent_level = 0)
    ),
    CONSTRAINT uq_tasks_id_level UNIQUE (id, level),
    CONSTRAINT fk_tasks_parent FOREIGN KEY (parent_id, parent_level)
        REFERENCES tasks (id, level) ON DELETE CASCADE,
    CONSTRAINT fk_tasks_rule FOREIGN KEY (recurrence_rule_id)
        REFERENCES recurrence_rules (id) ON DELETE SET NULL,
    CONSTRAINT uq_tasks_occurrence UNIQUE (recurrence_rule_id, occurrence_date)
);

CREATE INDEX ix_tasks_status_due ON tasks (status, due_date);
CREATE INDEX ix_tasks_completed_at ON tasks (completed_at);
CREATE INDEX ix_tasks_parent ON tasks (parent_id);
