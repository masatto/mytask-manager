CREATE TABLE areas (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(20)              NOT NULL,
    color      VARCHAR(10)              NOT NULL,
    position   INTEGER                  NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_areas_color CHECK (color IN ('blue', 'green', 'purple', 'orange', 'teal', 'pink', 'brown', 'gray'))
);

-- サブタスクは親と同じエリアを持つ（絞り込みを1件ずつの判定で済ませるため）。
-- エリアを消したときの付け替えはアプリで行う。ここの SET NULL は最後の防止策
ALTER TABLE tasks ADD COLUMN area_id BIGINT;
ALTER TABLE tasks ADD CONSTRAINT fk_tasks_area FOREIGN KEY (area_id) REFERENCES areas (id) ON DELETE SET NULL;
CREATE INDEX ix_tasks_area ON tasks (area_id);

-- ルールから生成するタスクは、ルールのエリアに入る
ALTER TABLE recurrence_rules ADD COLUMN area_id BIGINT;
ALTER TABLE recurrence_rules ADD CONSTRAINT fk_rules_area FOREIGN KEY (area_id) REFERENCES areas (id) ON DELETE SET NULL;

