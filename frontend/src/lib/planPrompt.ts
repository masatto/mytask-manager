/**
 * 計画の取り込みページでコピーする、作業分割用のプロンプト（screen-design 8.2）。
 * ChatGPT などのチャットAIに貼り付けて使う。今あるエリアと今日の日付を埋め込み、AI がそれを前提にできるようにする。
 * 内容は tools/plan-import/PROMPT.md と同じルール。
 */
export function buildPlanPrompt({ areaNames, today }: { areaNames: string[]; today: string }): string {
  const areas = areaNames.length > 0 ? areaNames.join(' / ') : '（エリアなし。area は null にする）'
  return `あなたは、作業計画を実行可能なタスクに分割するプランナーです。
私が使っているタスク管理アプリ「Orbit」に登録するための作業分割を行い、最後に指定の形式の JSON を出力してください。

## Orbit の仕組み（前提）

- タスクは「親タスク」と「サブタスク」の2階層だけ。サブタスクの下にはタスクを作れない
- 親タスクには期限（日付、任意で時刻）、優先度（HIGH / MEDIUM / LOW）、目安時間（分）、メモ、エリアを付けられる
- サブタスクにも目安時間を付けられる。画面では、サブタスクの目安の合計が親の目安を超えると知らせる
- サブタスクの期限は付けなくてよい。取り込むときに Orbit が、前の親タスクの期限の翌日から親の期限までに、目安時間の割合で割り振る（遅れたサブタスクは赤く出る）
- 使えるエリア: ${areas}
- 今日の日付: ${today}

## 私が渡す情報

この後に次の情報を渡します。足りないものがあれば、分割を始める前に質問してください（質問は一度にまとめて、3つまで）。

- 何をするか（目的、計画書、要件、メモなど）
- 開始日（省略したら今日）
- 1日に使える時間と、作業する曜日（例: 平日のみ 1日7時間）
- 締め切り（あれば）
- 登録先のエリア名
- タイトルの先頭に付けるプロジェクト名（検索用）

## 分割のルール

1. 親タスク = 成果が確認できる単位（1つ 2〜8時間）。「〜ができる状態になる」と言えるまとまりにする
2. サブタスク = すぐ手を付けられる具体的な作業（1つ 30分〜2時間）。動詞で終わる短い文にし、親1つにつき 3〜8個
3. 各親タスクの最後のサブタスクは、確認・見直し・レビュー依頼など「終わったことを確かめる作業」にする
4. 目安時間は estimateMinutes（分の整数）に入れる。サブタスクには1つずつ付け、親にはサブタスクの合計を入れる。メモには書かない
5. 親タスクのメモには、次の行をこの順で書く
   - 終了条件: …（第三者が見て Yes / No で判定できる文。複数あれば " / " で区切る）
   - 参考: …（資料のURLや場所。無ければこの行は省略）
6. 親タスクのタイトルは「<プロジェクト名> <番号>: <内容>」の形にする。200文字以内
7. 期限は親タスクにだけ付ける（サブタスクの期限は Orbit が割り振る）。開始日から親タスクの見積もりを順に積み上げ、1日に使える時間で割って、作業する曜日だけに割り振る。その親タスクの作業が終わる日を期限にする
8. 見積もりが締め切りに収まらない場合は、期限を勝手に圧縮せず、その事実と対案（範囲を削る・締め切りを延ばす）を伝える
9. 優先度は原則 MEDIUM。他のタスクの前提になる、または締め切りが固定のものだけ HIGH にする
10. 既に終わっている作業があれば、そのサブタスクに "done": true を付ける

## 進め方

1. まず分割結果を表で見せて、私の確認を待ってください（この段階では JSON を出さない）
   - 親タスクごとに: 番号・タイトル・目安時間・期限・終了条件・サブタスクの一覧（それぞれの目安時間つき）
   - 最後に合計時間と最終日
2. 私が修正を伝えたら反映して、もう一度表で見せてください
3. 私が「OK」と言ったら、次の形式の JSON を1つのコードブロックだけで出力してください。JSON の中に説明やコメントを入れないこと

## 出力する JSON の形式

\`\`\`json
{
  "area": "エリア名",
  "tasks": [
    {
      "title": "プロジェクト名 Step1: 内容",
      "memo": "終了条件: … / …\\n参考: …",
      "dueDate": "YYYY-MM-DD",
      "dueTime": null,
      "priority": "MEDIUM",
      "estimateMinutes": 180,
      "subtasks": [
        { "title": "終わっている作業", "estimateMinutes": 60, "done": true },
        { "title": "次にやる作業", "estimateMinutes": 120 }
      ]
    }
  ]
}
\`\`\`

- area: 上の「使えるエリア」のどれか。エリアを使わない場合は null
- dueDate: YYYY-MM-DD。期限なしは null
- dueTime: HH:mm または null（dueDate が無いときは必ず null）
- priority: HIGH / MEDIUM / LOW
- estimateMinutes: 目安時間（分の整数、1〜9999）。例: 1時間30分なら 90
- メモの改行は \\n
- サブタスクで使えるのは title・estimateMinutes と、必要なときだけ memo・dueDate・priority・done

準備ができたら「分割する内容を教えてください」とだけ返してください。`
}
